// Category pick strip ("Best overall", "Best for toddlers", …) — every
// pick is computed from the family-fit score over a data-backed subset.
function picksStrip(list, { withTravel = false } = {}) {
  const eligible = list.filter(familyEligible);
  const sorted = eligible.slice().sort(byScore);
  const picks = [];
  const used = new Set();
  const take = (label, arr, why) => {
    const p = arr.find((r) => !used.has(r.resort_id));
    if (!p) return;
    used.add(p.resort_id);
    picks.push({ label, r: p, why: why ? why(p) : whyItRanks(p) });
  };
  take("Best overall", sorted);
  take("Best luxury", sorted.filter((r) => Number(r.stars) >= 5));
  take("Best for toddlers", sorted.filter(toddlerFit));
  take("Best for families of 5", sorted.filter((r) => Number(r.family_max) >= 5));
  take("Best all-inclusive", sorted.filter((r) => r.all_inclusive));
  if (withTravel) {
    take("Best for an easy travel day",
      sorted.filter((r) => r.transfer_min != null && r.transfer_min <= 30),
      (p) => `Roughly ${p.transfer_min} minutes from ${p.airport_name || p.airport_iata} — minimal post-flight drive.`);
  }
  if (!picks.length) return "";
  return `<ul class="seo-picks">
${picks.map(({ label, r, why }) => `<li class="seo-pick">
  <span class="seo-pick-label">${esc(label)}</span>
  <a class="seo-pick-name" href="${resortPath(r)}">${esc(displayName(r))}</a>
  <span class="seo-pick-meta">${esc(r.country)}</span>
  <span class="seo-pick-why">${esc(why)}</span>
</li>`).join("\n")}
</ul>`;
}

