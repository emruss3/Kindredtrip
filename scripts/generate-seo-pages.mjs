// Defensive: even though the SQL snapshot already filters NOT
// service_excluded, drop any flagged rows here too in case the file is
// regenerated by a query that forgot the WHERE clause.
// Countries explicitly excluded from search/AI/SEO surfaces. Kept here
// alongside the resorts-seo.json filter so the exclusion applies even
// when the snapshot itself doesn't carry service_excluded (the JSON
// schema predates that DB column). DB-side, see the
// service_excluded migrations.
const EXCLUDED_COUNTRIES = new Set([
  "Cuba",          // US OFAC restrictions
  "Brazil",        // South America / Atlantic, not Caribbean
  "Ecuador",       // Pacific South America, not Caribbean
  "Peru",          // Pacific South America, not Caribbean
  "United States", // Florida Keys/coast, not Caribbean
]);
const resorts = JSON.parse(readFileSync(join(ROOT, "data/resorts-seo.json"), "utf8"))
  .filter((r) => r && r.service_excluded !== true && !EXCLUDED_COUNTRIES.has(r.country));

// Family-fit signals + recent reviews per resort (extracted from
// resort_family_signals + resort_reviews_raw). Used to render an
// AggregateRating + individual Review JSON-LD on each resort page,
// plus a visible "What families say" / "Recent guest reviews"
// section. Reviews are attributed to their original source per
// Google's review-snippet guidelines.
const reviewBundle = (() => {
  try {
    return JSON.parse(readFileSync(join(ROOT, "data/resort-review-seo.json"), "utf8"));
  } catch { return { signals: [], reviews: [] }; }
})();

// LiteAPI "hero" photo per matched resort (picked as mainPhoto:true or
// classOrder:0 from resort_rooms.photos). These are curated hotel
// photos — much better than Google Places exterior shots.
const liteapiHero = new Map();
try {
  const arr = JSON.parse(readFileSync(join(ROOT, "data/resort-liteapi-hero.json"), "utf8"));
  for (const row of arr) if (row?.resort_id && row?.url) liteapiHero.set(row.resort_id, row.url);
} catch { /* file optional */ }

// Max room occupancy ("sleeps N") per resort_id, for 4★+ resorts that
// sleep 5+. Sourced from Supabase cap_max_room_occupancy /
// family_room_max_occupancy (the snapshot's family_max column is empty).
// Attached to each resort below as r.sleeps so the large-family +
// family-of-5 themes work. Resorts not in this map get sleeps=0.
const sleeps5ById = (() => {
  try { return JSON.parse(readFileSync(join(ROOT, "data/resort-sleeps5.json"), "utf8")); }
  catch { return {}; }
})();
for (const r of resorts) {
  if (r && r.resort_id && sleeps5ById[r.resort_id] != null) {
    r.sleeps = Number(sleeps5ById[r.resort_id]) || 0;
  } else if (r) {
    // fall back to family_max if the snapshot ever carries it
    r.sleeps = r.family_max != null ? Number(r.family_max) || 0 : 0;
  }
}
const signalsByResort = new Map();
for (const s of reviewBundle.signals || []) signalsByResort.set(s.resort_id, s);
const reviewsByResort = new Map();
for (const r of reviewBundle.reviews || []) {
  if (!reviewsByResort.has(r.resort_id)) reviewsByResort.set(r.resort_id, []);
  reviewsByResort.get(r.resort_id).push(r);
}

// ---------- helpers ----------
const esc = (s) =>
  String(s ?? "").replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

function slugify(s) {
  return String(s ?? "")
    .normalize("NFKD").replace(/[̀-ͯ]/g, "")
    .replace(/\([^)]*\)/g, " ")          // drop parentheticals (date/age notes)
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)+/g, "")
    .slice(0, 80) || "resort";
}

