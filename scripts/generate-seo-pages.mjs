// The snapshot is the single source of truth for public counts. These
// regex patches are idempotent — they match ANY number in the known
// phrasings, so re-running the generator keeps hand-maintained pages in
// sync as the catalogue grows.
function patchCounts() {
  const topCountries = countries
    .slice()
    .sort((a, b) => byCountry.get(b).length - byCountry.get(a).length)
    .slice(0, 15);
  const replacements = [
    // "Family resorts" counts only family-eligible properties; the total
    // catalogue size uses the neutral word "properties".
    [/\b\d[\d,]*\+ family resorts/g, `${STATS.familyDisplay} family resorts`],
    [/\b\d[\d,]*\+ family-friendly resorts/g, `${STATS.familyDisplay} family-friendly resorts`],
    [/\b\d[\d,]*\+ family-friendly Caribbean resorts/g, `${STATS.familyDisplay} family-friendly Caribbean resorts`],
    [/\b\d[\d,]*\+ properties/g, `${STATS.resortsDisplay} properties`],
    // Generic "<n>+ resorts" (no qualifier) = total catalogue size. Runs
    // after the family-specific patterns, which consume their matches.
    [/\b\d[\d,]*\+ resorts\b/g, `${STATS.resortsDisplay} resorts`],
    [/\b\d+ Caribbean destinations/g, `${STATS.countries} Caribbean destinations`],
    [/\b\d+ destination airports/g, `${STATS.airports} destination airports`],
    [/\b\d+ airports/g, `${STATS.airports} airports`],
    [/\b\d+ countries/g, `${STATS.countries} countries`],
    [/\b\d+ other Caribbean countries/g, `${Math.max(0, STATS.countries - 5)} other Caribbean countries`],
    [/All \d+ Caribbean and Caribbean-adjacent destinations, including [^.<"]+\./g,
     `All ${STATS.countries} Caribbean and Caribbean-adjacent destinations, including ${topCountries.slice(0, 12).join(", ")}, and more.`],
    [/<div class="stat-num">\d[\d,]*\+<\/div><div class="stat-label">Family resorts compared<\/div>/g,
     `<div class="stat-num">${STATS.familyDisplay}</div><div class="stat-label">Family resorts compared</div>`],
    [/<div class="stat-num">\d[\d,]*\+?<\/div><div class="stat-label">Caribbean countries<\/div>/g,
     `<div class="stat-num">${STATS.countries}</div><div class="stat-label">Caribbean countries</div>`],
    [/<div class="stat-num">\d[\d,]*\+?<\/div><div class="stat-label">Destination airports<\/div>/g,
     `<div class="stat-num">${STATS.airports}</div><div class="stat-label">Destination airports</div>`],
  ];
  // Homepage destination chip nav — regenerate the whole link list from
  // the snapshot so names + per-country counts always match /caribbean.
  const destLinks = countries
    .map((c) => `<a href="${countryPath(c)}" class="seo-dest-link">${esc(c)} <span>(${byCountry.get(c).filter(familyEligible).length})</span></a>`)
    .join("");
  for (const file of ["index.html", "about.html"]) {
    const p = join(ROOT, file);
    if (!existsSync(p)) continue;
    let html = readFileSync(p, "utf8");
    const before = html;
    for (const [re, sub] of replacements) html = html.replace(re, sub);
    html = html.replace(
      /<div class="seo-dest-links">[\s\S]*?<\/div>/,
      `<div class="seo-dest-links">${destLinks}</div>`,
    );
    if (html !== before) {
      writeFileSync(p, html);
      console.log(`Patched counts in ${file}`);
    }
  }
  // llms.txt speaks to answer engines — keep its counts and destination
  // list in lockstep with the same snapshot.
  const llmsPath = join(ROOT, "llms.txt");
  if (existsSync(llmsPath)) {
    let txt = readFileSync(llmsPath, "utf8");
    const before = txt;
    for (const [re, sub] of replacements) txt = txt.replace(re, sub);
    txt = txt.replace(/\b\d+ Caribbean destinations: [^\n]+/g,
      `${STATS.countries} Caribbean destinations: ${topCountries.slice(0, 12).join(", ")}, and others`);
    txt = txt.replace(/\b\d+ destinations\b/g, `${STATS.countries} destinations`);
    txt = txt.replace(/\b\d[\d,]*\+ US origin airports/g, `50+ US origin airports`);
    if (txt !== before) {
      writeFileSync(llmsPath, txt);
      console.log("Patched counts in llms.txt");
    }
  }
}

