// ---------- country hub ----------
function countryStats(list) {
  return {
    total: list.length,
    kc: list.filter((r) => r.kids_club).length,
    beach: list.filter((r) => r.on_beach).length,
    wp: list.filter((r) => r.water_park).length,
    infant: list.filter(toddlerFit).length,
    ai: list.filter((r) => r.all_inclusive).length,
    sleeps5: list.filter((r) => Number(r.family_max) >= 5).length,
    connecting: list.filter((r) => r.connecting).length,
    adultsOnly: list.filter((r) => !familyEligible(r)).length,
    // Dedupe by IATA code — some rows carry the airport name, some only
    // the code, and "Sangster, MBJ" would be the same airport twice.
    // Prefer the named label when any row provides it.
    airports: (() => {
      const byKey = new Map();
      for (const r of list) {
        const key = r.airport_iata || r.airport_name;
        if (!key) continue;
        const label = airportDisplay(r);
        const prev = byKey.get(key);
        if (!prev || (label && label.includes("—") && !prev.includes("—"))) byKey.set(key, label);
      }
      return [...byKey.values()];
    })(),
    transfers: list.map((r) => r.transfer_min).filter((t) => t != null).sort((a, b) => a - b),
  };
}

