// Short "why it ranks" line built only from confirmed fields.
function whyItRanks(r) {
  const parts = [];
  if (r.kids_club) parts.push("kids club");
  if (r.on_beach) parts.push("beachfront");
  if (r.water_park) parts.push("water park");
  if (Number(r.family_max) >= 6) parts.push(`rooms for ${r.family_max}`);
  else if (Number(r.family_max) >= 5) parts.push("family-of-5 rooms");
  if (r.connecting) parts.push("connecting rooms");
  if (r.all_inclusive) parts.push("all-inclusive rates seen");
  if (toddlerFit(r)) parts.push("toddler-ready");
  const r5 = ratingTo5(r.rating);
  const feats = parts.slice(0, 3).join(", ");
  if (feats && r5 != null) return `${feats[0].toUpperCase()}${feats.slice(1)} — rated ${r5}/5 by guests.`;
  if (feats) return `${feats[0].toUpperCase()}${feats.slice(1)}.`;
  if (r5 != null) return `Strong guest rating (${r5}/5) in ${r.country}.`;
  return `Family-friendly pick in ${r.country}.`;
}

// Honest watch-outs. Every line is grounded in a field we track (or in
// the absence of one).
function watchOutsFor(r) {
  const out = [];
  if (!familyEligible(r)) out.push("Positioned as adults-only — confirm the age policy before booking with kids.");
  if (!r.kids_club) out.push("No confirmed kids club in our data.");
  if (r.transfer_min != null && r.transfer_min > 90) out.push(`Long airport transfer — roughly ${r.transfer_min} minutes from ${r.airport_name || r.airport_iata || "the nearest airport"}.`);
  if (!r.on_beach) out.push("Not directly on the beach in our data.");
  if (r.rating != null && Number(r.rating) < 75) out.push(`Guest rating (${ratingTo5(r.rating)}/5) is below the catalogue average.`);
  if (r.family_max != null && Number(r.family_max) <= 4) out.push(`Largest room configuration we track sleeps ${r.family_max} — larger families may need two rooms.`);
  if (knownFieldCount(r) < 5) out.push("We have limited family-fit data for this resort — verify details before booking.");
  return out;
}

// "Best for" chips derived only from confirmed fields.
function bestForList(r) {
  const out = [];
  if (!familyEligible(r)) return ["Adults-only escapes", "Multi-generation groups traveling without young kids"];
  if (toddlerFit(r) && r.kids_club) out.push("Families with toddlers and preschoolers");
  else if (toddlerFit(r)) out.push("Families traveling with infants or toddlers");
  if (r.water_park) out.push("Kids who live for waterslides");
  if (Number(r.family_max) >= 6) out.push(`Big families (rooms sleep up to ${r.family_max})`);
  else if (Number(r.family_max) >= 5) out.push("Families of 5");
  if (r.on_beach) out.push("Beach-first trips");
  if (r.all_inclusive) out.push("All-inclusive budgeting");
  if (r.transfer_min != null && r.transfer_min <= 30) out.push("Short travel days (quick airport transfer)");
  if (!out.length && r.kids_club) out.push("Families who want organized kids' activities");
  if (!out.length) out.push("Families comparing total trip cost across the Caribbean");
  return out.slice(0, 4);
}

// Noun-phrase version of the top watch-out, for the "Not ideal for"
// verdict row.
function notIdealFor(r) {
  if (!familyEligible(r)) return "Families with young kids — adults-only positioning";
  if (!r.kids_club) return "Parents who need drop-off childcare";
  if (!r.on_beach) return "Beach-first families";
  if (r.transfer_min != null && r.transfer_min > 90) return "Kids who melt down on long transfer drives";
  if (r.family_max != null && Number(r.family_max) <= 4 && !r.connecting) return "Families of 5+ wanting a single room";
  return "Families who need every detail confirmed up front — verify specifics when booking";
}

function skipIfList(r) {
  const out = [];
  if (!familyEligible(r)) out.push("You're traveling with children — this property is positioned adults-only.");
  if (!r.kids_club) out.push("You need drop-off childcare — no kids club is confirmed here.");
  if (!r.on_beach) out.push("Walking straight onto the sand is the whole point of your trip.");
  if (r.transfer_min != null && r.transfer_min > 90) out.push("Your kids melt down on long drives — the airport transfer is significant.");
  if (r.family_max != null && Number(r.family_max) <= 4 && !r.connecting) out.push("You're a family of 5+ and want to stay in one room.");
  if (!out.length) out.push("You want a guarantee on a specific room type — always confirm the exact room when booking.");
  return out.slice(0, 3);
}

// Best-ages line, grounded: we only claim age fit where a field supports it.
function bestAges(r) {
  if (!familyEligible(r)) return "Adults (18+) — adults-only positioning";
  const bits = [];
  if (toddlerFit(r)) bits.push("infants & toddlers");
  if (r.kids_club) bits.push("school-age kids");
  if (r.water_park) bits.push("tweens & teens");
  if (!bits.length) return null; // unknown — don't invent
  return bits.join(", ").replace(/^./, (c) => c.toUpperCase());
}

// Per-country hero photo — used as a fallback on resort pages that have
// neither a LiteAPI hero nor a Google Places photo of their own. Prefer
// the country's strongest LiteAPI hero so even fallbacks are curated
// hotel photography.
const countryHero = new Map();
for (const c of countries) {
  const list = byCountry.get(c) || [];
  const liteapiFirst = list.map((r) => liteapiHero.get(r.resort_id)).find(Boolean);
  if (liteapiFirst) { countryHero.set(c, liteapiFirst); continue; }
  const gpFirst = list.find((r) => r.photo_ref)?.photo_ref;
  if (gpFirst) countryHero.set(c, gpFirst);
}

// Priority chain for any resort: curated LiteAPI hero → Google Places
// (often older exterior photo) → country fallback. Returns whatever
// photoUrl() will accept — full https URL OR a Google Places ref.
function pageHero(resort) {
  if (!resort) return null;
  const la = liteapiHero.get(resort.resort_id);
  if (la) return la;
  if (resort.photo_ref) return resort.photo_ref;
  if (resort.country && countryHero.has(resort.country)) return countryHero.get(resort.country);
  return null;
}

