// ---------- transfer-time sanity check ----------
// A few source rows carry impossible transfer times (e.g. "3 min from
// MBJ" for a resort 39 miles away). We approximate each destination
// airport's location as the median position of its short-transfer
// resorts, then drop any transfer_min implying >80 mph by road. When the
// resort is >150 miles from its claimed airport cluster, the airport
// mapping itself is untrustworthy, so we drop that too. Better no claim
// than a fake fact.
(() => {
  const toRad = (d) => (d * Math.PI) / 180;
  const miles = (a, b, c, e) => {
    const dl = toRad(c - a), dg = toRad(e - b);
    const x = Math.sin(dl / 2) ** 2 + Math.cos(toRad(a)) * Math.cos(toRad(c)) * Math.sin(dg / 2) ** 2;
    return 2 * 3958.8 * Math.asin(Math.sqrt(x));
  };
  const median = (arr) => { const s = arr.slice().sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };
  const groups = new Map();
  for (const r of resorts) {
    if (r.airport_iata && r.transfer_min != null && r.lat != null) {
      if (!groups.has(r.airport_iata)) groups.set(r.airport_iata, []);
      groups.get(r.airport_iata).push(r);
    }
  }
  let dropped = 0;
  for (const [, rs] of groups) {
    const near = rs.filter((r) => r.transfer_min <= 20);
    if (near.length < 3) continue;
    const alat = median(near.map((r) => Number(r.lat)));
    const alng = median(near.map((r) => Number(r.lng)));
    for (const r of rs) {
      const m = miles(alat, alng, Number(r.lat), Number(r.lng));
      const mph = m / (r.transfer_min / 60);
      if (m > 150) { r.transfer_min = null; r.airport_iata = null; r.airport_name = null; dropped++; }
      else if (m > 12 && mph > 80) { r.transfer_min = null; dropped++; }
    }
  }
  if (dropped) console.log(`Sanity check: dropped ${dropped} implausible transfer/airport claims.`);
})();

