function haversineMiles(lat1, lng1, lat2, lng2) {
  const toRad = (d) => (d * Math.PI) / 180;
  const R = 3958.8;
  const dLat = toRad(lat2 - lat1), dLng = toRad(lng2 - lng1);
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}
// Distance-based ESTIMATE of nonstop flying time. Always labeled as an
// estimate in copy — we never claim a real airline route or schedule.
function estFlightLabel(miles) {
  if (!Number.isFinite(miles)) return null;
  const hours = 0.75 + miles / 460;
  const totalMin = Math.round((hours * 60) / 15) * 15;
  const h = Math.floor(totalMin / 60), m = totalMin % 60;
  return `≈${h}h${m ? ` ${m}m` : ""} est. nonstop flying time`;
}
function resortDistanceFrom(ap, r) {
  if (r.lat == null || r.lng == null) return null;
  return haversineMiles(ap.lat, ap.lng, Number(r.lat), Number(r.lng));
}

