// ---------- de-dupe ----------
// The catalogue still carries a handful of duplicate rows (same property
// ingested twice, usually one row much thinner than the other). Keep the
// row with the most confirmed data (tiebreak: more reviews) so we never
// publish two competing pages for one property.
const resorts = (() => {
  const keyOf = (r) => `${String(r.resort_name).replace(/\([^)]*\)/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-")}|${r.country}`;
  const richness = (r) =>
    ["rating", "stars", "transfer_min", "family_max", "liteapi_hotel_id", "photo_ref"].filter((k) => r[k] != null).length * 10 +
    ["kids_club", "on_beach", "water_park", "pool", "connecting", "infants", "cribs", "all_inclusive"].filter((k) => r[k]).length +
    Math.min(9, Math.log10(1 + Number(r.reviews || 0)));
  const best = new Map();
  for (const r of resortsRaw) {
    const k = keyOf(r);
    const prev = best.get(k);
    if (!prev || richness(r) > richness(prev)) best.set(k, r);
  }
  const out = [...best.values()];
  if (out.length !== resortsRaw.length) {
    console.log(`De-dupe: dropped ${resortsRaw.length - out.length} duplicate catalogue rows.`);
  }
  return out;
})();

